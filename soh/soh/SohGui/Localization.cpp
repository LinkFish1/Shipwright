static std::string TranslateImpl(const std::string& text) {
    if (text.empty()) {
        return text;
    }
    // The Interface Language combo box stores an integer key (0 = English, 1 = Simplified Chinese).
    int32_t lang = CVarGetInteger(CVAR_SETTING("Menu.InterfaceLanguage"), 0);
    if (lang == 1) {
        auto it = gChineseTable.find(text);
        if (it != gChineseTable.end()) {
            return it->second;
        }
    }
    return text;
}

// Decode a UTF-8 string and collect every non-ASCII codepoint it uses.
static void CollectCodepoints(const std::string& s, std::set<uint32_t>& out) {
    const unsigned char* p = reinterpret_cast<const unsigned char*>(s.data());
    size_t i = 0;
    while (i < s.size()) {
        unsigned char c = p[i];
        uint32_t cp;
        if (c < 0x80) {
            cp = c;
            i += 1;
        } else if ((c & 0xE0) == 0xC0) {
            cp = ((c & 0x1F) << 6) | (p[i + 1] & 0x3F);
            i += 2;
        } else if ((c & 0xF0) == 0xE0) {
            cp = ((c & 0x0F) << 12) | ((p[i + 1] & 0x3F) << 6) | (p[i + 2] & 0x3F);
            i += 3;
        } else if ((c & 0xF8) == 0xF0) {
            cp = ((c & 0x07) << 18) | ((p[i + 1] & 0x3F) << 12) | ((p[i + 2] & 0x3F) << 6) |
                 (p[i + 3] & 0x3F);
            i += 4;
        } else {
            i += 1;
            continue;
        }
        // Keep everything that isn't plain ASCII so the default font (which already
        // covers ASCII) is not duplicated, but CJK / fullwidth / curly quotes are.
        if (cp >= 0x80) {
            out.insert(cp);
        }
    }
}

void RegisterLocalization() {
    StringHelper::SetTranslator(TranslateImpl);
}

// Merge a Simplified-Chinese font into ImGui's default font so the menu can actually
// render Chinese glyphs. This is invoked from libultraship's Gui::Init (via the
// RegisterFontSetupCallback below), which runs AFTER the default + icon fonts are queued
// but BEFORE the atlas is built on the first frame — so the merged glyphs are included.
// We only merge the codepoints that appear in our translation table, which keeps the
// atlas small and startup fast.
static void MergeCjkFont() {
    static bool sFontMerged = false;
    if (sFontMerged) {
        return;
    }
    sFontMerged = true;

    // Candidate locations, in priority order:
    //   1. next to the executable (most reliable — GetModuleFileName based)
    //   2. the app/working directory
    //   3. the current working directory (bare name)
    // GetAppDirectoryPath() returns "." on Windows, so we must NOT rely on it alone;
    // GetAppBundlePath() resolves to the real exe directory.
    std::vector<std::string> candidates = {
        Ship::Context::GetPathRelativeToAppBundle("DroidSansFallback.ttf"),
        Ship::Context::GetPathRelativeToAppDirectory("DroidSansFallback.ttf"),
        "DroidSansFallback.ttf",
    };

    std::string fontPath;
    std::error_code ec;
    bool found = false;
    for (const auto& cand : candidates) {
        if (std::filesystem::exists(fontPath = cand, ec)) {
            found = true;
            break;
        }
    }
    if (!found) {
        SPDLOG_WARN("[Localization] DroidSansFallback.ttf not found (searched next to soh.exe, the "
                    "app directory, and the working directory); Simplified-Chinese menu text will "
                    "render as boxes. Copy the font next to soh.exe.");
        return;
    }
    SPDLOG_INFO("[Localization] Loading CJK font from '{}'", fontPath);

    std::set<uint32_t> codepoints;
    for (const auto& pair : gChineseTable) {
        CollectCodepoints(pair.second, codepoints);
    }

    // IMPORTANT: ImGui's AddFont* only stores a *pointer* to the glyph-ranges array in the
    // ImFontConfig; it does NOT copy the data. The atlas is actually built later, on the first
    // frame (after this function returns). If we used a local vector here it would be destroyed
    // and the ranges pointer would dangle, so the CJK glyphs would silently fail to be packed
    // and Chinese would render as boxes. Keep the array alive in static storage.
    static std::vector<ImWchar> ranges;
    ranges.clear();
    for (uint32_t cp : codepoints) {
        ranges.push_back(static_cast<ImWchar>(cp));
        ranges.push_back(static_cast<ImWchar>(cp));
    }
    ranges.push_back(0);

    ImGuiIO& io = ImGui::GetIO();
    ImFontConfig cfg;
    cfg.MergeMode = true;
    cfg.PixelSnapH = true;
    // Match the default menu font size (13.0f, see libultraship Gui.cpp).
    ImFont* font = io.Fonts->AddFontFromFileTTF(fontPath.c_str(), 13.0f, &cfg, ranges.data());
    if (font == nullptr) {
        SPDLOG_WARN("[Localization] Failed to load DroidSansFallback.ttf from '{}'; "
                    "Simplified-Chinese menu text will render as boxes.",
                    fontPath);
    } else {
        SPDLOG_INFO("[Localization] Merged {} Simplified-Chinese glyphs from '{}' into the default font.",
                    codepoints.size(), fontPath);
    }
}

// Resolve the CJK font location (next to the exe is most reliable). Returns false if not found.
static bool FindCjkFontPath(std::string& outPath) {
    std::vector<std::string> candidates = {
        Ship::Context::GetPathRelativeToAppBundle("DroidSansFallback.ttf"),
        Ship::Context::GetPathRelativeToAppDirectory("DroidSansFallback.ttf"),
        "DroidSansFallback.ttf",
    };
    std::error_code ec;
    for (const auto& cand : candidates) {
        if (std::filesystem::exists(outPath = cand, ec)) {
            return true;
        }
    }
    return false;
}

// Build (once, cached) a glyph-range array covering ImGui's common simplified-Chinese set
// UNIONed with every character that actually appears in our Simplified-Chinese translation
// table. The "common" set alone is only ~2500 chars and is missing many real characters
// (e.g. U+9891 频, which appears in our table), which is exactly why some Chinese text showed
// as boxes. Unioning the table's own codepoints guarantees every translated string has its
// glyphs packed into the atlas. The result is kept in static storage because ImGui only stores
// the pointer, and the atlas is not built until the first frame.
static const ImWchar* BuildCjkRanges(ImFontAtlas* atlas) {
    static std::vector<ImWchar> ranges;
    if (!ranges.empty()) {
        return ranges.data();
    }

    std::set<ImWchar> cps;
    // 1) ImGui's common simplified-Chinese set (covers any Chinese text, not just our table).
    if (atlas != nullptr) {
        const ImWchar* common = atlas->GetGlyphRangesChineseSimplifiedCommon();
        for (int i = 0; common[i]; i += 2)
            for (ImWchar c = common[i]; c <= common[i + 1]; ++c) cps.insert(c);
    }
    // 2) Every codepoint used in our Simplified-Chinese translation table, so even chars the
    //    common set omits (like 频) are guaranteed to have a glyph.
    std::set<uint32_t> tableCps;
    for (const auto& pair : gChineseTable) {
        CollectCodepoints(pair.second, tableCps);
    }
    for (uint32_t cp : tableCps) {
        if (cp <= 0xFFFF) {
            cps.insert(static_cast<ImWchar>(cp));
        }
    }
    // 3) Pack into (lo,hi) runs, merging adjacent codepoints to keep the array compact.
    auto it = cps.begin();
    while (it != cps.end()) {
        ImWchar lo = *it;
        ImWchar hi = lo;
        auto nxt = std::next(it);
        while (nxt != cps.end() && *nxt <= hi + 1) {
            hi = *nxt;
            ++nxt;
        }
        ranges.push_back(lo);
        ranges.push_back(hi);
        it = nxt;
    }
    ranges.push_back(0);
    SPDLOG_INFO("[Localization] CJK glyph range built: {} distinct codepoints.", cps.size());
    return ranges.data();
}

// Merge Simplified-Chinese glyphs into a specific UI font (the menu renders with the
// Montserrat/Inconsolata fonts created in OTRGlobals, NOT ImGui's built-in default font),
// so Chinese text actually shows. The glyph range is the common-simplified-Chinese set UNIONed
// with every character used in our translation table (see BuildCjkRanges). The font data is read
// once and cached in static storage, and the atlas is told to own its own copy so the buffer
// can be released. The merge is sized to `size` so the glyphs match the target font's metrics.
bool MergeSimplifiedChineseInto(ImFont* dstFont, float size) {
    if (dstFont == nullptr) {
        SPDLOG_WARN("[Localization] MergeSimplifiedChineseInto called with a null font.");
        return false;
    }

    std::string fontPath;
    if (!FindCjkFontPath(fontPath)) {
        SPDLOG_WARN("[Localization] DroidSansFallback.ttf not found (searched next to soh.exe, the "
                    "app directory, and the working directory); Simplified-Chinese menu text will "
                    "render as boxes. Copy the font next to soh.exe.");
        return false;
    }

    // Read the TTF into static storage so it stays alive for as long as the atlas needs it.
    static std::vector<unsigned char> sFontData;
    if (sFontData.empty()) {
        std::ifstream f(fontPath, std::ios::binary);
        if (!f) {
            SPDLOG_WARN("[Localization] Could not open DroidSansFallback.ttf at '{}'.", fontPath);
            return false;
        }
        sFontData.assign(std::istreambuf_iterator<char>(f), std::istreambuf_iterator<char>());
        if (sFontData.empty()) {
            SPDLOG_WARN("[Localization] DroidSansFallback.ttf at '{}' is empty.", fontPath);
            return false;
        }
        SPDLOG_INFO("[Localization] Loaded CJK font '{}' ({} bytes).", fontPath, sFontData.size());
    }

    ImGuiIO& io = ImGui::GetIO();
    ImFontConfig cfg;
    cfg.MergeMode = true;
    cfg.DstFont = dstFont;       // merge into the SPECIFIC UI font, not just the default
    cfg.FontDataOwnedByAtlas = false; // atlas makes its own copy, so sFontData need not persist
    cfg.PixelSnapH = true;
    const ImWchar* ranges = BuildCjkRanges(io.Fonts);
    ImFont* result =
        io.Fonts->AddFontFromMemoryTTF(sFontData.data(), static_cast<int>(sFontData.size()), size, &cfg, ranges);
    if (result == nullptr) {
        SPDLOG_WARN("[Localization] Failed to merge CJK glyphs into a UI font (size {}).", size);
        return false;
    }
    SPDLOG_INFO("[Localization] Merged Simplified-Chinese glyphs into a UI font (size {}).", size);
    return true;
}

